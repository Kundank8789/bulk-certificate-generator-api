from pathlib import Path
from reportlab.lib.pagesizes import landscape, A4
from reportlab.pdfgen import canvas
from reportlab.lib.units import mm

def generate_certificate(output_path: Path, recipient_name: str, course_name: str) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    c = canvas.Canvas(str(output_path), pagesize=landscape(A4))
    width, height = landscape(A4)

    c.setLineWidth(3)
    c.rect(12*mm, 12*mm, width-24*mm, height-24*mm)
    c.setFont("Helvetica-Bold", 30)
    c.drawCentredString(width/2, height-55*mm, "CERTIFICATE OF COMPLETION")
    c.setFont("Helvetica", 16)
    c.drawCentredString(width/2, height-78*mm, "This certificate is proudly presented to")
    c.setFont("Helvetica-Bold", 25)
    c.drawCentredString(width/2, height-102*mm, recipient_name)
    c.setFont("Helvetica", 15)
    c.drawCentredString(width/2, height-124*mm, f"for successfully completing: {course_name}")
    c.setFont("Helvetica", 10)
    c.drawCentredString(width/2, 30*mm, "Generated by Bulk Certificate Generator API")
    c.save()
